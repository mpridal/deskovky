// Renders the launcher icon from AppIconPainter into the Android resources.
//
//     flutter test tool/app_icon/generate_app_icon_test.dart
//
// Writes mipmap-*/ic_launcher.png (round, for old launchers),
// mipmap-*/ic_launcher_foreground.png (adaptive layer: the circle fills the
// 72 dp visible part of the 108 dp layer) and docs/design/app-icon-512.png.
// The adaptive icon's background is transparent, so the icon stays a circle
// whatever shape the launcher uses.
import 'dart:io';
import 'dart:ui' as ui;

import 'package:deskovky/ui_kit/brand/app_icon.dart';
import 'package:flutter/rendering.dart';
import 'package:flutter_test/flutter_test.dart';

const _res = 'android/app/src/main/res';
const _densities = {'mdpi': 1.0, 'hdpi': 1.5, 'xhdpi': 2.0, 'xxhdpi': 3.0, 'xxxhdpi': 4.0};

Future<void> _write(String path, int side, {double inset = 0}) async {
  final recorder = ui.PictureRecorder();
  final canvas = Canvas(recorder);
  final drawn = side - 2 * inset;
  canvas.translate(inset, inset);
  const AppIconPainter().paint(canvas, Size.square(drawn));
  final image = await recorder.endRecording().toImage(side, side);
  final png = await image.toByteData(format: ui.ImageByteFormat.png);
  image.dispose();
  File(path)
    ..parent.createSync(recursive: true)
    ..writeAsBytesSync(png!.buffer.asUint8List());
}

void main() {
  testWidgets('generate the launcher icon', (tester) async {
    await tester.runAsync(() async {
      for (final MapEntry(key: name, value: scale) in _densities.entries) {
        await _write('$_res/mipmap-$name/ic_launcher.png', (48 * scale).round());
        final layer = (108 * scale).round();
        await _write('$_res/mipmap-$name/ic_launcher_foreground.png', layer, inset: 18 * scale);
      }
      await _write('docs/design/app-icon-512.png', 512);
    });
    File('$_res/mipmap-anydpi-v26/ic_launcher.xml')
      ..parent.createSync(recursive: true)
      ..writeAsStringSync('''
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/app_icon/generate_app_icon_test.dart. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@android:color/transparent" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
''');
  });
}
