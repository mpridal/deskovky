import 'tables.dart';

part 'app_database.g.dart';

/// Local SQLite database. Every schema change bumps [schemaVersion], adds a
/// migration step and a schema snapshot in `drift_schemas/` (see CLAUDE.md).
@DriftDatabase(
  tables: [Players, AppSettings, GameSettingsLast, SavedSessions, Matches, MatchParticipants, PlayerCounters, EarnedBadges, PointsLedger, PlayerItems, SyncOps, FamilyDevices],
)
class AppDatabase extends _$AppDatabase {
  AppDatabase(super.executor);

  /// Database file name and directory. Both are pinned on purpose: an APK
  /// update keeps the app documents directory (`app_flutter/`), and the
  /// location must never follow a library default that could change.
  static const fileName = 'deskovky';
  static const databaseDirectory = getApplicationDocumentsDirectory;

  factory AppDatabase.open() => AppDatabase(
        driftDatabase(
          name: fileName,
          native: const DriftNativeOptions(databaseDirectory: databaseDirectory),
        ),
      );

  @override
  int get schemaVersion => 6;

  @override
  MigrationStrategy get migration => MigrationStrategy(
        onCreate: (m) => m.createAll(),
        // Step by step, each step with the tables as they were in its
        // version (app_database.steps.dart, generated by make-migrations).
        onUpgrade: stepByStep(
          // v2: remembered game setup and saved games in progress.
          from1To2: (m, schema) async {
            await m.createTable(schema.gameSettingsLast);
            await m.createTable(schema.savedSessions);
          },
          // v3: finished games, event counters and badges (milestone 6).
          from2To3: (m, schema) async {
            await m.createTable(schema.matches);
            await m.createTable(schema.matchParticipants);
            await m.createTable(schema.playerCounters);
            await m.createTable(schema.earnedBadges);
          },
          // v4: points ledger (milestone 7).
          from3To4: (m, schema) => m.createTable(schema.pointsLedger),
          // v5: bought avatar upgrades (milestone 7b).
          from4To5: (m, schema) => m.createTable(schema.playerItems),
          // v6: family sync – ids shared by all devices and the change log.
          // Existing data gets its ids and ops on first open (importLegacy).
          from5To6: (m, schema) async {
            await m.addColumn(schema.players, schema.players.uid);
            await m.addColumn(schema.matches, schema.matches.uid);
            await m.addColumn(schema.pointsLedger, schema.pointsLedger.uid);
            await m.createTable(schema.syncOps);
            await m.createTable(schema.familyDevices);
          },
        ),
        beforeOpen: (details) async {
          await customStatement('PRAGMA foreign_keys = ON');
          // v6: the data from before gets family ids and ops, once.
          if (details.hadUpgrade && (details.versionBefore ?? 6) < 6 && details.versionNow >= 6) await importLegacy(this);
        },
      );
}
