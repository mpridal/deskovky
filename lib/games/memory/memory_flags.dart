/// The "Vlajky" set of Pexeso: every state – the 193 UN members plus the
/// Vatican and Palestine – with its name in Czech, English and Spanish.
/// Flag pictures are `assets/games/memory/cards/flags/<code>.png` (flagcdn.com,
/// public domain, see `assets/games/memory/CREDITS.json`).
///
/// A game deals only a few of them, chosen afresh from the seed, so the flags
/// rotate from game to game. [MemoryFlag.family] names flags that look alike
/// on a small card; one game never deals two of a family.
class MemoryFlag {
  const MemoryFlag(this.code, this.cs, this.en, this.es, [this.family]);

  /// ISO 3166-1 alpha-2, lower case.
  final String code;
  final String cs;
  final String en;
  final String es;
  final String? family;

  String name(String language) => switch (language) {
    'cs' => cs,
    'es' => es,
    _ => en,
  };
}

